-- ============================================================================
-- 029_FEE_LEDGER.sql -- run after 028_admissions.sql
-- ============================================================================
-- Paste the whole file into the SQL editor and Run. Idempotent.
--
-- WHAT THIS FIXES
--
-- The fee module has bills but no account. Every "what does this family owe"
-- on every screen is a sum over challans rebuilt at render time, three
-- screens doing it three slightly different ways, and nothing can answer
-- "what did they owe on the first of August" at all.
--
-- This adds the account: one dated entry per thing that happened to a
-- student's money, and a balance that is a stored fact rather than a query.
--
--     date    entry                      debit    credit   balance
--     01 Jun  Tuition - June             4,500             4,500
--     01 Jul  Tuition - July             4,500             9,000
--     20 Oct  Payment - cash RC-0088              30,000  -20,500
--
-- Positive is owed. NEGATIVE IS CREDIT -- money the school is holding for
-- that family, which is the thing the system could not represent before.
--
-- NOTHING WRITES THIS BY HAND
--
-- Triggers mirror challans and payments into the ledger, and a third keeps
-- students.fee_balance in step with it. Two writers for one number is how
-- the number ends up wrong, so the app writes challans and payments exactly
-- as it does today and the ledger follows.
-- ============================================================================


-- ----------------------------------------------------------------------------
-- 1. The account
-- ----------------------------------------------------------------------------
-- One row per event. `amount` is signed -- a charge is positive, money
-- received is negative -- so the balance is SUM(amount) and nothing has to
-- know which column to look in.
CREATE TABLE IF NOT EXISTS public.fee_ledger (
  id          uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  -- The order entries happened in. created_at cannot do this job: now() is
  -- the TRANSACTION time, so a challan raised and paid in one request gets
  -- identical timestamps and the running balance below would order them by
  -- random uuid -- showing a payment above the charge it settled.
  seq         bigint GENERATED BY DEFAULT AS IDENTITY,
  school_id   uuid NOT NULL REFERENCES public.schools(id) ON DELETE CASCADE,
  student_id  uuid NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  entry_date  date NOT NULL DEFAULT CURRENT_DATE,
  kind        text NOT NULL CHECK (kind IN ('charge', 'payment', 'adjustment', 'opening')),
  amount      numeric(12, 2) NOT NULL,
  description text,
  -- What caused it. One of these is set for everything the triggers write;
  -- a manual adjustment has neither, which is how you tell it apart.
  challan_id  uuid REFERENCES public.fee_challans(id) ON DELETE CASCADE,
  payment_id  uuid REFERENCES public.fee_payments(id) ON DELETE CASCADE,
  created_by  uuid,
  updated_by  uuid,
  deleted_by  uuid,
  deleted_at  timestamptz,
  is_deleted  boolean NOT NULL DEFAULT false,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- One charge per challan and one receipt per payment: the triggers below
-- upsert on these, which is what makes them safe to re-run.
--
-- Not partial, deliberately. NULLs are distinct in a unique index, so the
-- many rows with no challan_id coexist happily -- and a partial index would
-- force every ON CONFLICT below to repeat the predicate to be inferable.
CREATE UNIQUE INDEX IF NOT EXISTS fee_ledger_one_per_challan
  ON public.fee_ledger (challan_id);
CREATE UNIQUE INDEX IF NOT EXISTS fee_ledger_one_per_payment
  ON public.fee_ledger (payment_id);

CREATE INDEX IF NOT EXISTS idx_fee_ledger_student
  ON public.fee_ledger (school_id, student_id, entry_date);

SELECT public.apply_tenant_rls('fee_ledger', 'fees.read', 'fees.write');
SELECT public.add_touch_trigger('fee_ledger');

-- The balance the screens read. Denormalised from the ledger on purpose:
-- every student row on every list wants it, and a correlated SUM per row is
-- how a student list becomes slow.
ALTER TABLE public.students
  ADD COLUMN IF NOT EXISTS fee_balance numeric(12, 2) NOT NULL DEFAULT 0;

COMMENT ON COLUMN public.students.fee_balance IS
  'Owed, in rupees. Negative means the school holds credit for this family. Maintained from fee_ledger by trigger -- never write it directly.';


-- ----------------------------------------------------------------------------
-- 2. The balance follows the ledger
-- ----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fee_balance_recalc()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $fn$
DECLARE
  v_student uuid;
BEGIN
  -- An UPDATE that moves an entry between students has to correct both.
  FOR v_student IN
    SELECT unnest(ARRAY[NEW.student_id, OLD.student_id]) WHERE true
  LOOP
    CONTINUE WHEN v_student IS NULL;

    UPDATE public.students s
       SET fee_balance = COALESCE((
             SELECT SUM(l.amount) FROM public.fee_ledger l
              WHERE l.student_id = v_student AND l.is_deleted = false
           ), 0)
     WHERE s.id = v_student;
  END LOOP;

  RETURN COALESCE(NEW, OLD);
END;
$fn$;

DROP TRIGGER IF EXISTS trg_fee_ledger_balance ON public.fee_ledger;
CREATE TRIGGER trg_fee_ledger_balance
  AFTER INSERT OR UPDATE OR DELETE ON public.fee_ledger
  FOR EACH ROW EXECUTE FUNCTION public.fee_balance_recalc();


-- ----------------------------------------------------------------------------
-- 3. A challan writes its charge
-- ----------------------------------------------------------------------------
-- The entry carries the challan's net_amount, so a late fee added in October
-- raises the June charge and the balance follows without a second entry to
-- reconcile. Cancelled or deleted removes the charge: fee_totals() has always
-- excluded those, and the ledger must agree with it.
CREATE OR REPLACE FUNCTION public.fee_challan_ledger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $fn$
DECLARE
  v_net numeric;
BEGIN
  IF NEW.is_deleted OR NEW.status = 'cancelled' THEN
    DELETE FROM public.fee_ledger WHERE challan_id = NEW.id;
    RETURN NEW;
  END IF;

  v_net := COALESCE(NEW.net_amount, NEW.total_amount, NEW.amount, 0);

  INSERT INTO public.fee_ledger
    (school_id, student_id, entry_date, kind, amount, description, challan_id)
  VALUES (
    NEW.school_id, NEW.student_id, COALESCE(NEW.issued_date, CURRENT_DATE), 'charge', v_net,
    COALESCE(NEW.description, initcap(NEW.fee_type)) ||
      CASE WHEN NEW.challan_number IS NOT NULL THEN ' · ' || NEW.challan_number ELSE '' END,
    NEW.id
  )
  ON CONFLICT (challan_id) DO UPDATE
    SET amount      = EXCLUDED.amount,
        description = EXCLUDED.description,
        entry_date  = EXCLUDED.entry_date,
        student_id  = EXCLUDED.student_id,
        is_deleted  = false,
        updated_at  = now();

  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS trg_fee_challans_ledger ON public.fee_challans;
CREATE TRIGGER trg_fee_challans_ledger
  AFTER INSERT OR UPDATE ON public.fee_challans
  FOR EACH ROW EXECUTE FUNCTION public.fee_challan_ledger();


-- ----------------------------------------------------------------------------
-- 4. A payment writes its receipt
-- ----------------------------------------------------------------------------
-- Negative, because money received reduces what is owed. This is the entry
-- that lets a balance go below zero, which is the whole point: a parent who
-- hands over more than the bill now has credit instead of an error message.
CREATE OR REPLACE FUNCTION public.fee_payment_ledger()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER SET search_path = public
AS $fn$
DECLARE
  v_student uuid;
BEGIN
  IF TG_OP = 'DELETE' THEN
    DELETE FROM public.fee_ledger WHERE payment_id = OLD.id;
    RETURN OLD;
  END IF;

  IF NEW.is_deleted THEN
    DELETE FROM public.fee_ledger WHERE payment_id = NEW.id;
    RETURN NEW;
  END IF;

  -- Older payments carry the student only through their challan.
  v_student := NEW.student_id;
  IF v_student IS NULL AND NEW.challan_id IS NOT NULL THEN
    SELECT c.student_id INTO v_student FROM public.fee_challans c WHERE c.id = NEW.challan_id;
  END IF;

  IF v_student IS NULL THEN
    RETURN NEW;
  END IF;

  INSERT INTO public.fee_ledger
    (school_id, student_id, entry_date, kind, amount, description, payment_id)
  VALUES (
    NEW.school_id, v_student, COALESCE(NEW.paid_at::date, CURRENT_DATE), 'payment',
    -ABS(COALESCE(NEW.amount_paid, 0)),
    'Payment · ' || COALESCE(NEW.method::text, 'cash') ||
      CASE WHEN NEW.receipt_no IS NOT NULL THEN ' · ' || NEW.receipt_no ELSE '' END,
    NEW.id
  )
  ON CONFLICT (payment_id) DO UPDATE
    SET amount      = EXCLUDED.amount,
        description = EXCLUDED.description,
        entry_date  = EXCLUDED.entry_date,
        student_id  = EXCLUDED.student_id,
        is_deleted  = false,
        updated_at  = now();

  RETURN NEW;
END;
$fn$;

DROP TRIGGER IF EXISTS trg_fee_payments_ledger ON public.fee_payments;
CREATE TRIGGER trg_fee_payments_ledger
  AFTER INSERT OR UPDATE OR DELETE ON public.fee_payments
  FOR EACH ROW EXECUTE FUNCTION public.fee_payment_ledger();


-- ----------------------------------------------------------------------------
-- 5. Everything that already happened
-- ----------------------------------------------------------------------------
-- The triggers only see what happens next, so the history goes in here. Safe
-- to re-run: both inserts conflict on the one-per-challan / one-per-payment
-- indexes.
-- Charges first, then receipts: within one date the sequence then reads
-- charge-before-payment, which is the order they happened in.
INSERT INTO public.fee_ledger
  (school_id, student_id, entry_date, kind, amount, description, challan_id)
SELECT c.school_id, c.student_id, COALESCE(c.issued_date, CURRENT_DATE), 'charge',
       COALESCE(c.net_amount, c.total_amount, c.amount, 0),
       COALESCE(c.description, initcap(c.fee_type)) ||
         CASE WHEN c.challan_number IS NOT NULL THEN ' · ' || c.challan_number ELSE '' END,
       c.id
  FROM public.fee_challans c
 WHERE c.is_deleted = false
   AND c.status <> 'cancelled'
ON CONFLICT (challan_id) DO NOTHING;

INSERT INTO public.fee_ledger
  (school_id, student_id, entry_date, kind, amount, description, payment_id)
SELECT p.school_id,
       COALESCE(p.student_id, c.student_id),
       COALESCE(p.paid_at::date, CURRENT_DATE), 'payment',
       -ABS(COALESCE(p.amount_paid, 0)),
       'Payment · ' || COALESCE(p.method::text, 'cash') ||
         CASE WHEN p.receipt_no IS NOT NULL THEN ' · ' || p.receipt_no ELSE '' END,
       p.id
  FROM public.fee_payments p
  LEFT JOIN public.fee_challans c ON c.id = p.challan_id
 WHERE p.is_deleted = false
   AND COALESCE(p.student_id, c.student_id) IS NOT NULL
ON CONFLICT (payment_id) DO NOTHING;

-- And one pass to set every balance, including the students with no entries.
UPDATE public.students s
   SET fee_balance = COALESCE((
         SELECT SUM(l.amount) FROM public.fee_ledger l
          WHERE l.student_id = s.id AND l.is_deleted = false
       ), 0);


-- ----------------------------------------------------------------------------
-- 6. Reading an account
-- ----------------------------------------------------------------------------
-- The ledger with a running balance, which is the thing a parent is shown and
-- the thing nobody could produce before. p_as_of answers "what did they owe
-- on the first of August".
CREATE OR REPLACE FUNCTION public.student_ledger(p_student uuid, p_as_of date DEFAULT NULL)
RETURNS TABLE (
  id uuid,
  entry_date date,
  kind text,
  description text,
  debit numeric,
  credit numeric,
  balance numeric,
  challan_id uuid,
  payment_id uuid
)
LANGUAGE sql STABLE
SECURITY DEFINER SET search_path = public, auth
AS $fn$
  SELECT l.id,
         l.entry_date,
         l.kind,
         l.description,
         CASE WHEN l.amount > 0 THEN  l.amount ELSE NULL END,
         CASE WHEN l.amount < 0 THEN -l.amount ELSE NULL END,
         SUM(l.amount) OVER (ORDER BY l.entry_date, l.seq
                             ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW),
         l.challan_id,
         l.payment_id
    FROM public.fee_ledger l
    JOIN public.students s ON s.id = l.student_id
   WHERE l.student_id = p_student
     AND l.is_deleted = false
     AND (p_as_of IS NULL OR l.entry_date <= p_as_of)
     -- Their own school only, and only to somebody who may read fees.
     AND s.school_id = public.current_school_id()
     AND public.has_permission('fees.read')
   ORDER BY l.entry_date, l.seq;
$fn$;

GRANT EXECUTE ON FUNCTION public.student_ledger(uuid, date) TO authenticated;


-- ============================================================================
-- 7. RESULT
-- ============================================================================
SELECT s.first_name || ' ' || COALESCE(s.last_name, '') AS student,
       count(l.id)                                       AS entries,
       COALESCE(SUM(l.amount) FILTER (WHERE l.amount > 0), 0) AS charged,
       COALESCE(-SUM(l.amount) FILTER (WHERE l.amount < 0), 0) AS received,
       s.fee_balance,
       CASE WHEN s.fee_balance < 0 THEN 'in credit'
            WHEN s.fee_balance > 0 THEN 'owes'
            ELSE 'settled' END AS state
  FROM public.students s
  LEFT JOIN public.fee_ledger l ON l.student_id = s.id AND l.is_deleted = false
 WHERE s.is_deleted = false
 GROUP BY s.id, s.first_name, s.last_name, s.fee_balance
 HAVING count(l.id) > 0
 ORDER BY s.fee_balance DESC;
